/**
 * 任务状态类型
 * - todo: 待办（未开始）
 * - doing: 进行中（正在处理）
 * - done: 已完成（已完成）
 */
export type TaskStatus = 'todo' | 'doing' | 'done'

/**
 * 任务优先级类型
 * - low: 低优先级
 * - medium: 中等优先级
 * - high: 高优先级
 */
export type TaskPriority = 'low' | 'medium' | 'high'

/**
 * 任务接口定义
 * 定义了任务管理系统中的核心数据结构
 */
export interface Task {
  /**
   * 任务唯一标识符
   * 类型：number（数字类型，便于生成和比较）
   * 设计原因：
   * - 必须唯一，用于区分不同的任务
   * - 使用 number 类型便于生成自增ID或使用时间戳
   * - 在 CRUD 操作中作为主键使用
   */
  id: number

  /**
   * 任务标题
   * 类型：string（字符串类型）
   * 设计原因：
   * - 任务的简短描述，便于快速识别任务内容
   * - 在列表视图中通常作为主要显示内容
   * - 必填字段，用于任务的基本识别
   */
  title: string

  /**
   * 任务详细描述
   * 类型：string（字符串类型）
   * 设计原因：
   * - 详细说明任务的具体内容和要求
   * - 提供比标题更丰富的信息，便于理解任务
   * - 可选或必填取决于业务需求，这里设为必填以保证数据完整性
   */
  description: string

  /**
   * 任务状态
   * 类型：TaskStatus（字面量联合类型）
   * 可选值：'todo' | 'doing' | 'done'
   * 设计原因：
   * - 使用字面量联合类型，确保状态值只能是指定的几个值之一
   * - TypeScript 可以在编译时检查状态值的正确性
   * - 三个状态覆盖了任务的基本生命周期
   * - 便于实现状态过滤、统计等功能
   */
  status: TaskStatus

  /**
   * 任务优先级
   * 类型：TaskPriority（字面量联合类型）
   * 可选值：'low' | 'medium' | 'high'
   * 设计原因：
   * - 帮助用户识别任务的重要性
   * - 可以用于任务排序、筛选、提醒等功能
   * - 使用字面量类型保证类型安全，避免拼写错误
   * - 便于在 UI 中用不同颜色/样式展示优先级
   */
  priority: TaskPriority

  /**
   * 创建时间（可选字段）
   * 类型：number（时间戳，毫秒）
   * 设计原因：
   * - 记录任务创建的时间，便于时间排序和统计
   * - 使用时间戳便于计算和存储
   * - 可选字段，向后兼容已有数据
   */
  createdAt?: number

  /**
   * 更新时间（可选字段）
   * 类型：number（时间戳，毫秒）
   * 设计原因：
   * - 记录任务最后修改时间，便于追踪任务变更
   * - 可以用于"最近修改"等功能
   * - 可选字段，向后兼容已有数据
   */
  updatedAt?: number
}
